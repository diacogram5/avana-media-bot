TRANSLATIONS = {"fa": FA, "en": EN, "ar": AR}

SUPPORTED = ("fa", "en", "ar")


def t(key: str, lang: str = "fa") -> str:
    """UI-chrome lookup. Unknown languages and missing keys fall back to
    Persian; a wholly unknown key returns the key itself (never a crash)."""
    table = TRANSLATIONS.get(lang) or FA
    return table.get(key) or FA.get(key, key)


def available_languages() -> list[str]:
    return list(TRANSLATIONS)


def toggle_texts(kind: str) -> dict[str, str]:
    """All language variants of a menu-collapse toggle label.

    Used to recognise the toggle button tap whatever language the user
    last rendered it in.
    """
    key = "m_toggle_close" if kind == "close" else "m_toggle_open"
    return {lg: t(key, lg) for lg in SUPPORTED}
