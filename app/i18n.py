"""i18n: Persian (fa) is the default and complete language.

English (en) and Arabic (ar) dictionaries ship alongside; ``t(key, lang)``
falls back to Persian for any missing key. Keys are grouped by feature:

- ``m_*``      bot menus, prompts, errors, statuses (app/bot/handlers.py,
               app/bot/logic.py, app/bot/media_send.py)
- ``cmn_*``    shared chrome words (set/unset, blocked, confirm-delete)
- ``plat_*``   platform brand names (Instagram/YouTube/…)
- ``lang_*``   language picker + language settings entry
- ``ftitle_*`` localized titles of the 10 persistent-menu buttons
               (fa keeps the admin-managed DB titles)
- ``dl_*``     smart downloader (app/features/downloader.py)
- ``adm_*``    admin panel (app/features/admin.py)
- ``bank_*``   superior-AI bank (app/features/bank.py)
- ``pro_*``    pro playlists/favorites (app/features/pro.py)
- ``lyr_*``    lyrics (app/search/lyrics.py)
- ``ad_*``     ad rendering (app/bot/ads.py)
- ``err_*``    brief one-line errors (also used by logic.brief_error)

HARD RULES (enforced by construction, not just convention):
- Song names, artist names, file names and any user content are NEVER
  translated: they travel as ``{title}``/``{artist}``/``{name}`` template
  placeholders and are interpolated after lookup.
- The language choice NEVER affects download/identify logic: no code in
  app/services/ or the identify paths branches on ``lang``; it only
  selects which UI-chrome string to render.
- ``fa`` strings are byte-identical to the pre-i18n Persian texts.

HONEST PERSISTENCE NOTE: the per-user language lives in bot.db
(migrations/016_user_language.sql). On Render's free tier the filesystem
is ephemeral, so a restart/redeploy wipes bot.db and the choice resets
to Persian ("fa") — the same platform limit as every other per-user
setting. Never claim cross-restart persistence on the free tier.
"""
